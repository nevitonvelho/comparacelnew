  const amazon=await page.evaluate(()=>globalThis.collectProduct());
  assert.equal(amazon.price,2999.99);assert.equal(amazon.source,'amazon');assert.equal(amazon.brand,'Samsung');
  await page.setContent('<span id="productTitle">Sem estoque</span>');
  assert.match(await page.evaluate(()=>{try{globalThis.collectProduct();return '';}catch(error){return error.message;}}),/preço principal/);
