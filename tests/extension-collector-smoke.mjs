  assert.equal(await popup.locator('#update-price').isVisible(),true);
  const offerRequest=await popup.evaluate(()=>globalThis.popupFixture.requests[0]);
  assert.equal(offerRequest.productId,'lavadora-importada');assert.equal(offerRequest.mode,'offer');assert.equal(offerRequest.affiliateUrl,'https://meli.la/owner');
  await popup.locator('#collect').click();
  await popup.waitForFunction(()=>document.querySelector('#match-status').textContent.includes('Já cadastrado:'));
  assert.equal(await popup.locator('#affiliate').inputValue(),'');
  await popup.locator('#update-price').click();
  await popup.waitForFunction(()=>globalThis.popupFixture.requests.length===2);
  assert.equal(await popup.evaluate(()=>globalThis.popupFixture.requests[1].mode),'price');
  await popup.waitForFunction(()=>!document.querySelector('#update-full').disabled);
  await popup.locator('#update-full').click();
  await popup.waitForFunction(()=>globalThis.popupFixture.requests.length===3);
  assert.equal(await popup.evaluate(()=>globalThis.popupFixture.requests[2].mode),'full');
  await popup.waitForFunction(()=>!document.querySelector('#collect').disabled);
  await popup.evaluate(()=>{
    globalThis.chrome.scripting.executeScript=async()=>[{result:{data:{version:1,source:'mercadolivre',pageUrl:'https://www.mercadolivre.com.br/p/MLB12345',capturedAt:new Date().toISOString(),name:'Lavadora',price:null,condition:'standard',brand:'Electrolux',description:'',imageUrl:'',specs:[]}}}];
  });
  await popup.locator('#collect').click();
  await popup.waitForFunction(()=>document.querySelector('#match-status').textContent.includes('Já cadastrado:'));
  assert.equal(await popup.locator('#price').textContent(),'Preço não disponível');
  assert.equal(await popup.locator('#update-price').isDisabled(),true);
  assert.equal(await popup.locator('#mark-unavailable').isVisible(),true);
  await popup.locator('#mark-unavailable').click();
  await popup.waitForFunction(()=>globalThis.popupFixture.requests.length===4);
  assert.equal(await popup.evaluate(()=>globalThis.popupFixture.requests[3].mode),'unavailable');
  await popup.waitForFunction(()=>!document.querySelector('#collect').disabled);
  await popup.evaluate(()=>{
    globalThis.currentFetch=globalThis.fetch;
    globalThis.fetch=async()=>new Response(JSON.stringify({error:'Operação inválida.'}),{status:400,headers:{'Content-Type':'application/json'}});
  });
  await popup.locator('#mark-unavailable').click();
  await popup.waitForFunction(()=>document.querySelector('#status').textContent.includes('API anterior'));
  assert.match(await popup.locator('#status').textContent(),/http:\/\/localhost:3000/);
  assert.equal(await popup.locator('#mark-unavailable').isDisabled(),false);
  await popup.evaluate(()=>{globalThis.fetch=globalThis.currentFetch;});
