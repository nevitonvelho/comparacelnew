  const html=(await readFile('extensions/comparacel-collector/popup.html','utf8')).replace('<script src="popup.js"></script>','').replace('<link rel="stylesheet" href="popup.css">','');
  await popup.setContent(html);
  await popup.evaluate(data=>{
    globalThis.draftStorage={};
    globalThis.chrome={storage:{local:{get:async()=>globalThis.draftStorage,set:async values=>Object.assign(globalThis.draftStorage,values)}},tabs:{query:async()=>[{id:1,url:data.pageUrl}]},scripting:{executeScript:async()=>[{result:{data}}]}};
    globalThis.fetch=async()=>{await new Promise(resolve=>setTimeout(resolve,200));return new Response(JSON.stringify({categories:[{id:'celulares',name:'Celulares'}]}),{headers:{'Content-Type':'application/json'}});};
  },mercado);
  await popup.addScriptTag({content:await readFile('extensions/comparacel-collector/popup.js','utf8')});
  await popup.locator('#key').fill('invalid');await popup.locator('#connect').click();
  assert.match(await popup.locator('#connection-status').textContent(),/Gere uma chave/);
  await popup.locator('#key').fill('ccx_'+'a'.repeat(64));await popup.locator('#connect').click();
  await popup.waitForFunction(()=>document.querySelector('#connect').disabled);
  assert.equal(await popup.locator('#connect').textContent(),'Conectando…');
  await popup.waitForFunction(()=>document.querySelector('#category').options.length===1);
  assert.equal(await popup.locator('#category').inputValue(),'celulares');
  await popup.waitForFunction(()=>!document.querySelector('#connect').disabled);
  await popup.locator('#connection').evaluate(node=>node.open=true);
  await popup.evaluate(()=>{globalThis.fetch=async()=>new Response(JSON.stringify({error:'Chave revogada.'}),{status:401,headers:{'Content-Type':'application/json'}});});
  await popup.locator('#connect').click();
  await popup.waitForFunction(()=>document.querySelector('#connection-status').textContent==='Chave revogada.');
  assert.equal(await popup.locator('#connect').isDisabled(),false);
  await popup.evaluate(()=>{
    const product={id:'lavadora-importada',name:'Lavadora no Comparacel',category:'lavadoras',offers:[{storeId:'amazon',price:2100,url:'https://amzn.to/owner'}],editPath:'/admin?produto=lavadora-importada'};
    globalThis.popupFixture={product,linked:false,requests:[]};
    globalThis.fetch=async(input,options)=>{
      const fixture=globalThis.popupFixture;const url=new URL(input);
      let data;
      if(options.method==='POST') {
        fixture.requests.push(JSON.parse(options.body));fixture.linked=true;
        data={product:fixture.product,message:'Salvo.',warnings:[]};
      } else if(url.searchParams.has('pageUrl'))data={product:fixture.linked?fixture.product:null,suggestions:fixture.linked?[]:[fixture.product]};
      else if(url.searchParams.has('q'))data={products:[fixture.product]};
      else data={categories:[{id:'lavadoras',name:'Lavadoras'}]};
      return new Response(JSON.stringify(data),{headers:{'Content-Type':'application/json'}});
    };
  });
  await popup.locator('#connect').click();
  await popup.waitForFunction(()=>document.querySelector('#connection-status').textContent==='Conectado. Categorias carregadas.');
  assert.equal(await popup.locator('#import').isVisible(),false);
  assert.equal(await popup.locator('#product').inputValue(),'lavadora-importada');
  assert.match(await popup.locator('#match-status').textContent(),/Possível produto já cadastrado/);
  assert.equal(await popup.locator('#search-controls').evaluate(node=>node.open),false);
  assert.equal(await popup.locator('#search').inputValue(),'Lavadora');
  assert.equal(await popup.locator('#update-price').isVisible(),true);
  assert.equal(await popup.locator('#save-offer').isVisible(),true);
  await popup.locator('#affiliate').fill('https://meli.la/owner');
