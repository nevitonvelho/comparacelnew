  await context.route('https://www.mercadolivre.com.br/**',route=>route.fulfill({contentType:'text/html',body:`<h1 class="ui-pdp-title">Lavadora</h1><div class="ui-pdp-price__second-line"><s class="andes-money-amount--previous">R$ 3.039</s><span class="andes-money-amount"><span class="andes-money-amount__fraction">2.089</span><span class="andes-money-amount__cents">90</span></span><span>no Pix</span></div><table class="ui-pdp-specs__table"><tr><th>Marca</th><td>Electrolux</td></tr><tr><th>Capacidade</th><td>18 kg</td></tr></table>`}));
