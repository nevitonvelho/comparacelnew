  assert.equal(modern.specs.length,4);assert.equal(modern.brand,'Apple');assert.ok(modern.specs.some(spec=>spec.name==='Memória interna' && spec.value==='128 GB'));
  await page.goto('https://www.mercadolivre.com.br/gz/account-verification');await page.addScriptTag({content:script});
  assert.match(await page.evaluate(()=>{try{globalThis.collectProduct();return '';}catch(error){return error.message;}}),/verificação/);
  await context.route('https://www.amazon.com.br/**',route=>route.fulfill({contentType:'text/html',body:`<span id="productTitle">Televisão</span><div id="corePrice_feature_div"><span class="a-price"><span class="a-price-whole">2.999</span><span class="a-price-fraction">99</span></span></div><table id="productDetails_techSpec_section_1"><tr><th>Marca</th><td>Samsung</td></tr></table>`}));
