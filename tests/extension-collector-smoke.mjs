    globalThis.chrome={storage:{local:{get:async()=>savedStorage,set:async values=>Object.assign(savedStorage,values)}},tabs:{query:async()=>[{id:1,url}]},scripting:{executeScript:async()=>{throw new Error('Não deve coletar novamente');}}};
