test("comunidade mostra automaticamente os pares mais comparados", async ({ page }) => {
  await page.goto('/comparar');
  const picker=page.getByLabel('Produto 1',{exact:true});
  await expect(picker).toBeVisible({timeout:30000});
  await expect.poll(()=>picker.locator('option').count()).toBeGreaterThan(3);
  const ids=await picker.locator('option').evaluateAll(options=>options.map(option=>(option as HTMLOptionElement).value).filter(Boolean));
  await page.goto(`/comparar/${ids[0]}-vs-${ids[1]}`);
  await expect(page.locator('.comparison-engagement .engagement-counts')).toBeVisible({timeout:30000});
  const response=await page.request.get('/api/popular-comparisons?category=celulares');
  expect(response.status()).toBe(200);
  const data=await response.json();
  expect(data.periodDays).toBe(7);
  expect(data.comparisons.length).toBeGreaterThan(0);
  expect(data.comparisons.every((item:{category:string;productIds:string[];views:number})=>item.category==='celulares'&&item.productIds.length===2&&item.views>0)).toBe(true);
  expect(data.comparisons[0]).not.toHaveProperty('authorUid');
  await page.goto('/comunidade');
  const ranking=page.getByRole('region',{name:'Comparações mais acessadas'});
  await expect(ranking.getByRole('heading',{name:'Mais comparados'})).toBeVisible();
  await expect(ranking.locator('.popular-pair').first()).toBeVisible({timeout:30000});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await ranking.screenshot({path:'test-results/popular-comparisons-mobile.png'});
});
