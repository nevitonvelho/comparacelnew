import { test, expect } from "@playwright/test";

test("seleção, troca, comparação completa e navegação", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/comparar");
  const first = page.getByLabel("Produto 1", { exact: true });
  await expect(first).toBeVisible({timeout:30000});
  await expect.poll(() => first.locator("option").count()).toBeGreaterThan(3);
  const ids = await first.locator("option").evaluateAll(options => options.map(option => (option as HTMLOptionElement).value).filter(Boolean));
  await first.selectOption(ids[0]);
  const second = page.getByLabel("Produto 2", { exact: true });
  await second.selectOption(ids[1]);
  // Replacing a filled slot must immediately select the newly chosen product.
  await second.selectOption(ids[2]);
  await expect(first).toHaveValue(ids[0]);
  await expect(second).toHaveValue(ids[2]);
  await page.getByRole("link", { name: "Ver comparação completa" }).click();
  await expect(page).toHaveURL(new RegExp(`/comparar/${[ids[0], ids[2]].sort().join("-vs-")}$`));
  await expect(page.getByRole("table").first()).toBeVisible();
  await page.getByLabel("Mostrar só diferenças").check();
  await page.getByRole("link", { name: "Ver ficha e ofertas" }).first().click();
  await expect(page).toHaveURL(new RegExp(`/produto/${[ids[0], ids[2]].sort()[0]}$`));
  await expect(page.getByRole("heading", { name: "Ficha técnica completa" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Remover da comparação", exact: false }).first()).toBeVisible();
  await page.getByRole("link", { name: "Comparar", exact: false }).first().click();
  await expect(first).toHaveValue(ids[0]);
  await expect(second).toHaveValue(ids[2]);
  await page.reload();
  await expect(first).toHaveValue(ids[0]);
  await expect(second).toHaveValue(ids[2]);
  expect(errors).toEqual([]);
});

